#!/usr/bin/env bash
# Generate OTMS Part-3 test evidence into docs/reports/.
# Run from the repository root after backend/ and frontend/ are merged to main.
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"
STAMP="$(date +%Y%m%d-%H%M%S)"
OUT="docs/reports/${STAMP}"
mkdir -p "$OUT"

echo "== Backend: unit tests + JaCoCo coverage =="
if [ -d backend ]; then
  (cd backend && ./mvnw -B clean test)
  mkdir -p "$OUT/unit-backend"
  cp -R backend/target/surefire-reports "$OUT/unit-backend/"
  cp -R backend/target/site/jacoco "$OUT/backend-jacoco"
else
  echo "backend/ not present on this branch — skipping (run on main after PR #3 merges)."
fi

echo "== Frontend: unit tests + v8 coverage =="
if [ -d frontend ]; then
  (cd frontend && CI=true npm test && CI=true npm run test:coverage)
  mkdir -p "$OUT/unit-frontend"
  cp -R frontend/coverage "$OUT/frontend-coverage"
else
  echo "frontend/ not present on this branch — skipping (run on main after PR #4 merges)."
fi

cat > "$OUT/README.md" <<EOF
# OTMS Test Reports — ${STAMP}

Generated by scripts/generate-reports.sh.

| Report | Deliverable | Location |
|---|---|---|
| Unit Test Report (backend) | Part-3 2(b)i | unit-backend/surefire-reports |
| Unit Test Report (frontend) | Part-3 2(b)i | unit-frontend (vitest stdout) |
| Code Coverage Report | Part-3 2(b)iii | backend-jacoco/index.html, frontend-coverage/index.html |
| Branch Coverage Report | Part-3 2(b)iv | backend-jacoco — JaCoCo "Branches" column |

The System Validation Report (Part-3 2(b)ii) is produced by running
docs/reports/system-validation.postman_collection.json against a live
instance (see docs/reports/README.md).
EOF

echo "Reports written to ${OUT}/"
echo "Commit them with: git add docs/reports && git commit -m 'Add test reports ${STAMP}'"
