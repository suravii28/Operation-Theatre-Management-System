-- Equipment inventory and surgery assignments (OTMS-F-015).
CREATE TABLE equipment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    type VARCHAR(255) NOT NULL,
    available BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_equipment_available_name ON equipment (available, name);

CREATE TABLE surgery_equipment (
    surgery_id BIGINT NOT NULL,
    equipment_id BIGINT NOT NULL,
    CONSTRAINT pk_surgery_equipment PRIMARY KEY (surgery_id, equipment_id),
    CONSTRAINT fk_surgery_equipment_surgery FOREIGN KEY (surgery_id) REFERENCES surgeries (id) ON DELETE CASCADE,
    CONSTRAINT fk_surgery_equipment_equipment FOREIGN KEY (equipment_id) REFERENCES equipment (id)
);

CREATE INDEX idx_surgery_equipment_equipment ON surgery_equipment (equipment_id);

-- Notifications generated by scheduling and emergency workflows (OTMS-F-018).
CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(50) NOT NULL,
    message VARCHAR(500) NOT NULL,
    surgery_id BIGINT,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_notifications_created_at ON notifications (created_at DESC);
CREATE INDEX idx_notifications_unread ON notifications (is_read, created_at DESC);
