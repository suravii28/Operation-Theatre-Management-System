CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE theatres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    speciality VARCHAR(255) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE surgeries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_name VARCHAR(255) NOT NULL,
    procedure_name VARCHAR(255) NOT NULL,
    lead_surgeon_id BIGINT NOT NULL,
    theatre_id BIGINT NOT NULL,
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NOT NULL,
    status VARCHAR(50) NOT NULL,
    emergency BOOLEAN NOT NULL DEFAULT FALSE,
    notes VARCHAR(255),
    CONSTRAINT fk_surgeries_lead_surgeon FOREIGN KEY (lead_surgeon_id) REFERENCES users (id),
    CONSTRAINT fk_surgeries_theatre FOREIGN KEY (theatre_id) REFERENCES theatres (id),
    CONSTRAINT chk_surgeries_time CHECK (end_time > start_time)
);

CREATE INDEX idx_surgeries_start_time ON surgeries (start_time);
CREATE INDEX idx_surgeries_theatre_time ON surgeries (theatre_id, start_time, end_time);
CREATE INDEX idx_surgeries_surgeon_time ON surgeries (lead_surgeon_id, start_time, end_time);
